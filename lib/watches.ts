export function getWatch(slug: string): Watch | undefined {
  return watches.find((watch) => watch.slug === slug);
}

export function getBrandWatches(brandSlug: string): Watch[] {
  return watches.filter((watch) => watch.brand === brandSlug);
}

export function getFeaturedWatches(): Watch[] {
  return featuredSlugs
    .map((slug) => getWatch(slug))
    .filter((watch): watch is Watch => Boolean(watch));
}

export function getNewArrivals(): Watch[] {
  return newArrivalSlugs
    .map((slug) => getWatch(slug))
    .filter((watch): watch is Watch => Boolean(watch));
}

export function getRelatedWatches(watch: Watch, limit = 4): Watch[] {
  const sameBrand = watches.filter(
    (item) => item.brand === watch.brand && item.slug !== watch.slug,
  );
  const sameFamily = watches.filter(
    (item) =>
      item.slug !== watch.slug &&
      item.brand !== watch.brand &&
      (item.gender === watch.gender || item.movement === watch.movement),
  );
  return [...sameBrand, ...sameFamily].slice(0, limit);
}

