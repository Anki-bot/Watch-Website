import type { Watch, WatchImage } from "./types";
import { tissotGallery } from "./tissot-gallery";
import { armaniGallery } from "./armani-gallery";
import { tommyGallery } from "./tommy-gallery";
import { fossilGallery } from "./fossil-gallery";

type GallerySourceItem = {
  src: string;
  thumb: string;
  alt: string;
  group: string;
};

/**
 * Builds a product photo set from a brand's in-store photo library.
 * `preferred` is a filename fragment that should appear first.
 */
function imagesFrom(
  source: GallerySourceItem[],
  group: string,
  preferred?: string,
): WatchImage[] {
  const items = source.filter((item) => item.group === group);
  const images = items.map((item) => ({
    src: item.src,
    thumb: item.thumb,
    alt: item.alt,
  }));

  if (preferred) {
    const index = items.findIndex((item) => item.src.includes(preferred));
    if (index > 0) {
      images.unshift(...images.splice(index, 1));
    }
  }

  return images;
}

function galleryImages(group: string, preferred?: string): WatchImage[] {
  return imagesFrom(tissotGallery, group, preferred);
}

function armaniImages(group: string, preferred?: string): WatchImage[] {
  return imagesFrom(armaniGallery, group, preferred);
}

function tommyImages(group: string, preferred?: string): WatchImage[] {
  return imagesFrom(tommyGallery, group, preferred);
}

function fossilImages(group: string, preferred?: string): WatchImage[] {
  return imagesFrom(fossilGallery, group, preferred);
}

